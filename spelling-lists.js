// ======================================================
// PARSE ONE LIST
// ======================================================

function parseSpellingList(listKey) {

    const list =
        spellingLists[listKey];


    if (!list) {

        throw new Error(
            "Spelling list not found: "
            + listKey
        );

    }


    const words =
        list.words
            .trim()
            .split("\n")
            .map(line => {

                const parts =
                    line.split("\t");


                return {

                    word:
                        parts[0].trim(),

                    definition:
                        parts.length > 1
                            ? parts
                                .slice(1)
                                .join("\t")
                                .trim()
                            : ""

                };

            })
            .filter(
                item => item.word
            );


    return {

        key:
            listKey,

        name:
            list.name,

        type:
            list.type,

        words:
            words

    };

}


// ======================================================
// GET AVAILABLE LISTS
// ======================================================

function getAvailableSpellingLists() {

    return Object.keys(
        spellingLists
    )
    .map(key => {

        const parsed =
            parseSpellingList(
                key
            );


        return {

            key:
                key,

            name:
                parsed.name,

            type:
                parsed.type,

            wordCount:
                parsed.words.length,

            vocabCount:
                parsed.words.filter(
                    item =>
                        item.definition
                ).length

        };

    });

}


